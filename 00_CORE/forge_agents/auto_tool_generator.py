"""
auto_tool_generator.py — Detect repetitive tasks and generate local tools
==========================================================================
Scans forge_fingerprint for tasks executed 3+ times. If no local tool exists,
generates a Python script under 00_CORE/forge_agents/tools/ and registers it
in 05_STATE/tool_index.json.

Usage:
    python auto_tool_generator.py              # scan + generate
    python auto_tool_generator.py --dry-run    # scan only
    python auto_tool_generator.py --scan       # show repetitive candidates
"""

from __future__ import annotations
import json
import logging
import os
import re
import sys
from datetime import datetime
from pathlib import Path
from typing import Optional

FORGE_ROOT = Path(__file__).resolve().parent.parent.parent
TOOLS_DIR = FORGE_ROOT / "00_CORE" / "forge_agents" / "tools"
TOOLS_DIR.mkdir(parents=True, exist_ok=True)
TOOL_INDEX = FORGE_ROOT / "05_STATE" / "tool_index.json"
FINGERPRINT_DB = FORGE_ROOT / "05_STATE" / "execution_fingerprints.json"

logging.basicConfig(level=logging.INFO, format="%(message)s")
logger = logging.getLogger("auto_tool_gen")


def load_fingerprints() -> dict:
    """Load execution fingerprints database."""
    if not FINGERPRINT_DB.exists():
        return {}
    try:
        data = json.loads(FINGERPRINT_DB.read_text(encoding="utf-8"))
        if isinstance(data, dict):
            return data
        return {}
    except Exception:
        return {}


def load_tool_index() -> dict:
    """Load existing tool index."""
    if not TOOL_INDEX.exists():
        return {"tools": [], "updated": ""}
    try:
        data = json.loads(TOOL_INDEX.read_text(encoding="utf-8"))
        if isinstance(data, list):
            return {"tools": data, "updated": ""}
        return data
    except Exception:
        return {"tools": [], "updated": ""}


def save_tool_index(index: dict) -> None:
    """Save tool index."""
    index["updated"] = datetime.now().isoformat()
    TOOL_INDEX.write_text(
        json.dumps(index, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )


def find_repetitive_tasks(fingerprints: dict, min_hits: int = 3) -> list[dict]:
    """Find tasks that have been executed min_hits+ times."""
    repetitive = []
    for key, value in fingerprints.items():
        if not isinstance(value, dict):
            continue
        hit_count = value.get("hit_count", 0)
        if hit_count >= min_hits:
            repetitive.append({
                "task_pattern": key,
                "hit_count": hit_count,
                "last_seen": value.get("last_seen", ""),
                "avg_tokens": value.get("avg_tokens", 0),
                "total_cost": value.get("total_cost", 0.0),
            })
    repetitive.sort(key=lambda x: -x["hit_count"])
    return repetitive


def tool_already_exists(task_pattern: str, tool_index: dict) -> bool:
    """Check if a tool already handles this task pattern."""
    pattern_lower = task_pattern.lower()
    for tool in tool_index.get("tools", []):
        tool_name = tool.get("name", "").lower()
        tool_desc = tool.get("description", "").lower()
        tool_keywords = [kw.lower() for kw in tool.get("keywords", [])]

        # Check if task pattern matches tool
        if any(kw in pattern_lower for kw in tool_keywords):
            return True
        if tool_name in pattern_lower or pattern_lower in tool_desc:
            return True
    return False


def infer_tool_type(task_pattern: str) -> str:
    """Infer what kind of tool to generate from the task pattern."""
    pattern = task_pattern.lower()

    if any(kw in pattern for kw in ["parse", "log", "extract", "regex"]):
        return "parser"
    if any(kw in pattern for kw in ["format", "convert", "transform"]):
        return "formatter"
    if any(kw in pattern for kw in ["scrape", "fetch", "download", "api"]):
        return "fetcher"
    if any(kw in pattern for kw in ["report", "summary", "generate"]):
        return "generator"
    if any(kw in pattern for kw in ["validate", "check", "verify"]):
        return "validator"
    if any(kw in pattern for kw in ["clean", "normalize", "sanitize"]):
        return "cleaner"

    return "utility"


