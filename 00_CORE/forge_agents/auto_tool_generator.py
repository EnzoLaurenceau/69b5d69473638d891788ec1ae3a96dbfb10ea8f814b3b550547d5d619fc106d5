def generate_tool(task: dict, tool_index: dict) -> Optional[dict]:
    """Generate a tool for a repetitive task. Returns tool metadata or None."""
    task_pattern = task["task_pattern"]
    tool_type = infer_tool_type(task_pattern)

    # Generate tool name
    words = re.findall(r'[a-z0-9]+', task_pattern.lower())[:4]
    tool_name = "_".join(words) if words else f"auto_tool_{len(tool_index.get('tools', []))}"
    safe_name = re.sub(r'[^a-z0-9_]', '_', tool_name)

    # Check if file already exists
    tool_path = TOOLS_DIR / f"{safe_name}.py"
    if tool_path.exists():
        logger.info(f"  skip {safe_name} — file already exists")
        return None

    # Generate code
    code = generate_tool_code(task_pattern, tool_type, safe_name)
    tool_path.write_text(code, encoding="utf-8")
    logger.info(f"  ✓ generated {tool_path.name} (type={tool_type})")

    # Return metadata for tool_index
    return {
        "name": safe_name,
        "description": f"Auto-generated for: {task_pattern[:100]}",
        "type": tool_type,
        "path": str(tool_path.relative_to(FORGE_ROOT)),
        "keywords": words,
        "hit_count_when_generated": task["hit_count"],
        "generated_at": datetime.now().isoformat(),
        "avg_tokens_saved": task.get("avg_tokens", 0),
    }


def main():
    import argparse
    parser = argparse.ArgumentParser(description="Auto tool generator")
    parser.add_argument("--dry-run", action="store_true", help="Scan only, don't generate")
    parser.add_argument("--scan", action="store_true", help="Show repetitive candidates")
    parser.add_argument("--min-hits", type=int, default=3, help="Min hits to consider repetitive")
    args = parser.parse_args()

    logger.info("=" * 60)
    logger.info("AUTO TOOL GENERATOR")
    logger.info("=" * 60)

    # Load data
    fingerprints = load_fingerprints()
    tool_index = load_tool_index()

    logger.info(f"\nFingerprints: {len(fingerprints)} entries")
    logger.info(f"Existing tools: {len(tool_index.get('tools', []))}")

    # Find repetitive tasks
    repetitive = find_repetitive_tasks(fingerprints, min_hits=args.min_hits)
    logger.info(f"Repetitive tasks (>{args.min_hits} hits): {len(repetitive)}")

    if not repetitive:
        logger.info("\nNo repetitive tasks found. Nothing to generate.")
        return

    # Filter out tasks that already have tools
    candidates = [
        t for t in repetitive
        if not tool_already_exists(t["task_pattern"], tool_index)
    ]
    logger.info(f"Candidates (no existing tool): {len(candidates)}")

    if args.scan or args.dry_run:
        logger.info("\n── Repetitive Tasks ──")
        for t in repetitive:
            has_tool = "✓" if tool_already_exists(t["task_pattern"], tool_index) else "✗"
            logger.info(f"  [{has_tool}] {t['hit_count']}x | {t['task_pattern'][:60]}")
            logger.info(f"      avg_tokens={t['avg_tokens']} cost=${t['total_cost']:.4f}")
        if args.dry_run:
            logger.info("\n[DRY RUN] Would generate tools for candidates above.")
        return

    # Generate tools
    logger.info(f"\n── Generating {len(candidates)} tools ──")
    new_tools = []
    for task in candidates:
        tool_meta = generate_tool(task, tool_index)
        if tool_meta:
            new_tools.append(tool_meta)

    # Update tool index
    if new_tools:
        tool_index.setdefault("tools", []).extend(new_tools)
        save_tool_index(tool_index)
        logger.info(f"\n✓ {len(new_tools)} tools generated and registered")
        logger.info(f"  Tools dir: {TOOLS_DIR}")
        logger.info(f"  Index: {TOOL_INDEX}")
    else:
        logger.info("\nNo new tools generated.")


if __name__ == "__main__":
    main()
