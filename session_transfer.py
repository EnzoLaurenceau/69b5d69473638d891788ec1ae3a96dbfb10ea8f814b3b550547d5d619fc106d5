"""
session_transfer.py — OptiForge Session Transfer for Hermes
============================================================
Auto-génère un brief structuré quand le ceiling est atteint.
Auto-détecte les briefs au démarrage d'une nouvelle session.

Usage:
  python session_transfer.py generate --session-id <id> --tasks <json>
  python session_transfer.py check
  python session_transfer.py index
"""

import json
import sys
import datetime
from pathlib import Path

FORGE_ROOT = Path(__file__).parent
BRIEFS_DIR = FORGE_ROOT / "session-transfer" / "briefs"
BRIEFS_DIR.mkdir(parents=True, exist_ok=True)
INDEX_FILE = BRIEFS_DIR / "INDEX.md"
TASK_LOG_DIR = FORGE_ROOT / "05_STATE"


def get_latest_brief() -> Path | None:
    """Retourne le brief le plus récent ou None."""
    briefs = sorted(BRIEFS_DIR.glob("*.md"), reverse=True)
    # Exclure INDEX.md
    briefs = [b for b in briefs if b.name != "INDEX.md"]
    return briefs[0] if briefs else None


def generate_brief(session_id: str, tasks: list[dict], ceiling: int = 50_000) -> Path:
    """Génère un brief de transfert structuré."""
    ts = datetime.datetime.now()
    date_str = ts.strftime("%Y-%m-%d-%H%M")
    total_tokens = sum(t.get("tokens", 0) for t in tasks)

    # Déterminer le projet depuis les tâches
    project = "FORGE"
    for t in tasks:
        if "craft" in t.get("task", "").lower():
            project = "CYW"
            break
        if "bounty" in t.get("task", "").lower():
            project = "BBH"
            break

    # Nom du fichier
    subject = tasks[0]["task"] if tasks else "session"
    filename = f"{date_str}--{project}--{subject}.md"
    brief_path = BRIEFS_DIR / filename

    # Colonnes kanban
    done = [t for t in tasks if t.get("status") == "done"]
    doing = [t for t in tasks if t.get("status") == "in_progress"]
    blocked = [t for t in tasks if t.get("status") == "blocked"]
    todo = [t for t in tasks if t.get("status") == "pending"]

    lines = [
        f"# Session Transfer Brief",
        f"> Generated: {ts.strftime('%Y-%m-%d %H:%M')} | Session: {session_id}",
        f"> Ceiling: {ceiling:,} | Used: {total_tokens:,} | Efficiency: {((ceiling - total_tokens) / ceiling * 100):.0f}%",
        "",
        "## Objective",
        f"Continue work from session {session_id}. See task breakdown below.",
        "",
        "## State Summary",
        "",
        f"| Status | Count | Tokens |",
        f"|--------|-------|--------|",
        f"| ✅ Done | {len(done)} | {sum(t['tokens'] for t in done):,} |",
        f"| 🔄 Doing | {len(doing)} | {sum(t['tokens'] for t in doing):,} |",
        f"| 🔴 Blocked | {len(blocked)} | {sum(t['tokens'] for t in blocked):,} |",
        f"| 📋 Todo | {len(todo)} | {sum(t['tokens'] for t in todo):,} |",
        "",
        "## Tasks Completed",
    ]

    for t in done:
        lines.append(f"- ✅ **{t['task']}** ({t['tokens']:,} tok)")

    if doing:
        lines.append("")
        lines.append("## In Progress (RESUME THESE)")
        for t in doing:
            lines.append(f"- 🔄 **{t['task']}** ({t['tokens']:,} tok) — {t.get('notes', '')}")

    if blocked:
        lines.append("")
        lines.append("## Blocked")
        for t in blocked:
            lines.append(f"- 🔴 **{t['task']}** — {t.get('notes', 'unknown blocker')}")

    if todo:
        lines.append("")
        lines.append("## Next Sprint (TODO)")
        for t in todo:
            lines.append(f"- 📋 **{t['task']}** (est. {t['tokens']:,} tok)")

    lines.append("")
    lines.append("## Optimizations Applied")
    lines.append("- Caveman mode (short fragments, no filler)")
    lines.append("- Local tools before LLM (search_files, terminal)")
    lines.append("- File output > inline content")
    lines.append("- 50K token ceiling per sub-session")
    lines.append("")
    lines.append("## First Action in New Session")
    if doing:
        lines.append(f"Resume: **{doing[0]['task']}**")
    elif todo:
        lines.append(f"Start: **{todo[0]['task']}**")
    else:
        lines.append("All tasks done. Review report and plan next sprint.")
    lines.append("")
    lines.append("---")
    lines.append(f"*Auto-generated by OptiForge session_transfer.py*")

    brief_path.write_text("\n".join(lines), encoding="utf-8")

    # Update INDEX.md
    _update_index(filename, ts, project, subject, total_tokens)

    return brief_path


def _update_index(filename: str, ts: datetime.datetime, project: str, subject: str, tokens: int):
    """Met à jour INDEX.md avec le nouveau brief."""
    entry = f"- [{ts.strftime('%Y-%m-%d %H:%M')} · {project}] {subject} ({tokens:,} tok) — [open]({filename})\n"

    if INDEX_FILE.exists():
        content = INDEX_FILE.read_text(encoding="utf-8")
        # Insérer après le header
        lines = content.split("\n")
        header_end = 0
        for i, line in enumerate(lines):
            if line.startswith("- ["):
                header_end = i
                break
        lines.insert(header_end, entry)
        INDEX_FILE.write_text("\n".join(lines), encoding="utf-8")
    else:
        INDEX_FILE.write_text(f"# Briefs Index — chronological (newest first)\n\n{entry}", encoding="utf-8")


def check_pending() -> str | None:
    """Vérifie s'il y a un brief en attente. Retourne le contenu ou None."""
    brief = get_latest_brief()
    if brief:
        return brief.read_text(encoding="utf-8")
    return None


def load_task_log(session_id: str) -> list[dict]:
    """Charge le log des tâches depuis 05_STATE."""
    log_file = TASK_LOG_DIR / f"task_log_{session_id}.json"
    if log_file.exists():
        return json.loads(log_file.read_text(encoding="utf-8"))
    return []


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="OptiForge Session Transfer")
    sub = parser.add_subparsers(dest="cmd")

    gen = sub.add_parser("generate", help="Generate transfer brief")
    gen.add_argument("--session-id", required=True)
    gen.add_argument("--ceiling", type=int, default=50_000)
    gen.add_argument("--tasks-json", help="JSON string of tasks array")

    sub.add_parser("check", help="Check for pending brief")
    sub.add_parser("index", help="Show briefs index")

    args = parser.parse_args()

    if args.cmd == "generate":
        if args.tasks_json:
            tasks = json.loads(args.tasks_json)
        else:
            tasks = load_task_log(args.session_id)
        path = generate_brief(args.session_id, tasks, args.ceiling)
        print(f"💾 Brief generated → {path}")

    elif args.cmd == "check":
        content = check_pending()
        if content:
            print("📋 PENDING BRIEF DETECTED:")
            print(content)
        else:
            print("✅ No pending briefs.")

    elif args.cmd == "index":
        if INDEX_FILE.exists():
            print(INDEX_FILE.read_text(encoding="utf-8"))
        else:
            print("(no briefs yet)")
    else:
        parser.print_help()
